WITH ranked AS (
  SELECT c.C_NAME, SUM(o.O_TOTALPRICE) AS total,
         ROW_NUMBER() OVER (PARTITION BY c.C_NATIONKEY ORDER BY SUM(o.O_TOTALPRICE) DESC
                            ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS rn
  FROM TPCH.CUSTOMER c, TPCH.ORDERS o
  WHERE o.O_CUSTKEY = c.C_CUSTKEY
  GROUP BY GROUPING SETS ((c.C_NAME, c.C_NATIONKEY), (c.C_NATIONKEY), ())
)
SELECT * FROM ranked WHERE rn <= 5 QUALIFY ROW_NUMBER() OVER (ORDER BY total DESC) <= 100;
